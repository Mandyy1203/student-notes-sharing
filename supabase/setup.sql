-- Student Notes Sharing System: initial database + storage security setup
-- Run this entire script once in Supabase SQL Editor for a fresh project.
-- It does not create an administrator automatically; see make_admin.sql.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  role text not null default 'student' check (role in ('student','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.subjects (
  id bigint generated by default as identity primary key,
  name text not null,
  branch text not null default 'ENTC',
  semester integer not null check (semester between 1 and 8),
  created_at timestamptz not null default now(),
  unique(name, branch, semester)
);

create table if not exists public.notes (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 120),
  description text not null default '' check (char_length(description) <= 500),
  subject_id bigint references public.subjects(id) on delete set null,
  branch text not null default 'ENTC',
  semester integer not null check (semester between 1 and 8),
  file_path text not null unique,
  file_size bigint not null check (file_size > 0 and file_size <= 10485760),
  uploaded_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create index if not exists notes_created_at_idx on public.notes(created_at desc);
create index if not exists notes_subject_id_idx on public.notes(subject_id);
create index if not exists notes_uploaded_by_idx on public.notes(uploaded_by);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, role)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name',''), 'student')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create or replace function public.is_admin(check_user_id uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = check_user_id and p.role = 'admin'
  );
$$;

revoke all on function public.is_admin(uuid) from public;
grant execute on function public.is_admin(uuid) to authenticated;

alter table public.profiles enable row level security;
alter table public.subjects enable row level security;
alter table public.notes enable row level security;

drop policy if exists "profiles_select_own_or_admin" on public.profiles;
create policy "profiles_select_own_or_admin" on public.profiles
for select to authenticated
using (id = (select auth.uid()) or (select public.is_admin()));

drop policy if exists "profiles_update_own_name" on public.profiles;
create policy "profiles_update_own_name" on public.profiles
for update to authenticated
using (id = (select auth.uid()))
with check (id = (select auth.uid()) and role = 'student');

drop policy if exists "subjects_read_authenticated" on public.subjects;
create policy "subjects_read_authenticated" on public.subjects
for select to authenticated using (true);

drop policy if exists "subjects_admin_insert" on public.subjects;
create policy "subjects_admin_insert" on public.subjects
for insert to authenticated with check ((select public.is_admin()));

drop policy if exists "subjects_admin_update" on public.subjects;
create policy "subjects_admin_update" on public.subjects
for update to authenticated using ((select public.is_admin()))
with check ((select public.is_admin()));

drop policy if exists "subjects_admin_delete" on public.subjects;
create policy "subjects_admin_delete" on public.subjects
for delete to authenticated using ((select public.is_admin()));

drop policy if exists "notes_read_authenticated" on public.notes;
create policy "notes_read_authenticated" on public.notes
for select to authenticated using (true);

drop policy if exists "notes_insert_own" on public.notes;
create policy "notes_insert_own" on public.notes
for insert to authenticated
with check (uploaded_by = (select auth.uid()));

drop policy if exists "notes_delete_owner_or_admin" on public.notes;
create policy "notes_delete_owner_or_admin" on public.notes
for delete to authenticated
using (uploaded_by = (select auth.uid()) or (select public.is_admin()));

-- Private PDF bucket. The browser uploads under {authenticated-user-uuid}/{unique-filename}.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('notes-pdfs', 'notes-pdfs', false, 10485760, array['application/pdf'])
on conflict (id) do update
set public = false, file_size_limit = 10485760, allowed_mime_types = array['application/pdf'];

drop policy if exists "notes_pdf_read_authenticated" on storage.objects;
create policy "notes_pdf_read_authenticated" on storage.objects
for select to authenticated
using (bucket_id = 'notes-pdfs');

drop policy if exists "notes_pdf_insert_own_folder" on storage.objects;
create policy "notes_pdf_insert_own_folder" on storage.objects
for insert to authenticated
with check (
  bucket_id = 'notes-pdfs'
  and (storage.foldername(name))[1] = (select auth.uid())::text
);

drop policy if exists "notes_pdf_update_own_folder" on storage.objects;
create policy "notes_pdf_update_own_folder" on storage.objects
for update to authenticated
using (bucket_id = 'notes-pdfs' and (storage.foldername(name))[1] = (select auth.uid())::text)
with check (bucket_id = 'notes-pdfs' and (storage.foldername(name))[1] = (select auth.uid())::text);

drop policy if exists "notes_pdf_delete_owner_or_admin" on storage.objects;
create policy "notes_pdf_delete_owner_or_admin" on storage.objects
for delete to authenticated
using (
  bucket_id = 'notes-pdfs'
  and (
    (storage.foldername(name))[1] = (select auth.uid())::text
    or (select public.is_admin())
  )
);

grant usage on schema public to authenticated;
grant select on public.profiles, public.subjects, public.notes to authenticated;
grant update (full_name) on public.profiles to authenticated;
grant insert on public.notes to authenticated;
grant delete on public.notes to authenticated;
grant insert, update, delete on public.subjects to authenticated;
grant usage, select on all sequences in schema public to authenticated;

